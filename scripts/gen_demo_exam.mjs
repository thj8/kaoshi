// ---------- 3. 建赛与出题 ----------
if (SINGLE.length !== 10 || MULTI.length !== 10) throw new Error('题量必须是 10 单选 + 10 多选')
for (const [c] of [...SINGLE, ...MULTI]) {
  if ([...c].length < 50) throw new Error('题干不足 50 字: ' + c.slice(0, 20) + '…')
}

const quiz = (await j('POST', '/api/admin/quiz', {
  title: TITLE, description: '网络安全方向 · 20 题 150 分 · 30 分钟 · 选择即保存、交卷前可改答案',
  mode: 'exam', total_time: 1800, per_question_time: 30,
  show_answer: true, show_analysis: true, show_ranking: true,
}, at)).data

let sort = 0
const mk = async (type, pool, i, score) => {
  const [content, answer, options, analysis] = pool[i]
  const r = await j('POST', `/api/admin/quiz/${quiz.code}/questions`, {
    type, content, answer, analysis, score, required: true,
    time_limit: 30, sort: ++sort,
    options: options.map((c, k) => ({ label: 'ABCD'[k], content: c })),
  }, at)
  if (r.code !== 0) throw new Error(`建题失败 #${sort}: ${r.msg}`)
}
for (let i = 0; i < 10; i++) await mk('single', SINGLE, i, 5)
for (let i = 0; i < 10; i++) await mk('multiple', MULTI, i, 10)

